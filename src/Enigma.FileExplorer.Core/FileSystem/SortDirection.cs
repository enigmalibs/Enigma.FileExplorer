namespace Enigma.FileExplorer.Core.FileSystem;

/// <summary>
/// The direction of a sort.
/// </summary>
public enum SortDirection
{
    /// <summary>
    /// Smallest, oldest or first in the alphabet first.
    /// </summary>
    Ascending,

    /// <summary>
    /// Largest, newest or last in the alphabet first.
    /// </summary>
    Descending,
}
